function randInt(max: number): number {
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    const buf = new Uint32Array(1);
    crypto.getRandomValues(buf);
    return buf[0]! % max;
  }
  return Math.floor(Math.random() * max);
}

export function getVisitorName(): string {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)?.trim();
    if (saved && saved.length <= 80) return saved;
  } catch {
    /* localStorage недоступен */
  }
  const adj = ADJECTIVES[randInt(ADJECTIVES.length)]!;
  const animal = ANIMALS[randInt(ANIMALS.length)]!;
  const tag = 10 + randInt(90);
  const generated = `${adj} ${animal} #${tag}`;
  try {
    localStorage.setItem(STORAGE_KEY, generated);
  } catch {
    /* игнорируем приватный режим */
  }
  return generated;
}

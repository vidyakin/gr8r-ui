/* Номера документов отдельной короткой транзакцией (задача: очередь проведений на счётчике).
 *
 * По умолчанию счётчик (организация, тип, год) увеличивается в транзакции проведения: строка заблокирована до коммита,
 * номера идут без пропусков, но всё проведение того же вида в организации стоит в очереди. API включает режим «номер
 * отдельно» на время запроса (withSeparateNumbering в tenant()): номер берётся своей транзакцией на отдельном маленьком
 * пуле и сразу коммитится — блокировка держится миллисекунды. Цена — пропуски: если проведение откатилось после выдачи
 * номера, номер пропадает. Воркер и системные проведения (биллинг, выписка, закрытие месяца) работают по-старому.
 *
 * Пул нумерации отдельный, иначе запрос, держащий соединение основного пула, ждал бы второе из того же пула —
 * при пачке запросов пул исчерпывается (см. tenant() в apps/api/src/middleware.ts).
 */
import { AsyncLocalStorage } from 'node:async_hooks';
import type { Sql } from './client';

const scope = new AsyncLocalStorage<Sql>();

/** Выполняет fn так, что номера документов внутри берутся отдельными транзакциями на пуле sql */
export function withSeparateNumbering<T>(sql: Sql, fn: () => Promise<T>): Promise<T> {
  return scope.run(sql, fn);
}

/** Выполняет fn с нумерацией в транзакции вызывающего — для пробного проведения с откатом (предпросмотр движений):
    иначе пробный расчёт тратил бы настоящий номер */
export function withInTransactionNumbering<T>(fn: () => Promise<T>): Promise<T> {
  return scope.exit(fn);
}

/** Пул нумерации текущего запроса или null — номер берётся в транзакции вызывающего */
export function separateNumberingSql(): Sql | null {
  return scope.getStore() ?? null;
}

/** Сколько отдельная транзакция ждёт строку счётчика: её может держать долгая транзакция воркера (сплошная нумерация) */
export const NUMBERING_LOCK_TIMEOUT = '5s';
